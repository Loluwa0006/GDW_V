FDiversionLockMenuState ComputeLockMenuState(const TArray<FDiversionLockMenuFileInfo>& InFiles)
{
	FDiversionLockMenuState State;
	for (const FDiversionLockMenuFileInfo& File : InFiles)
	{
		if (!File.bIsLocked)
		{
			State.LockTargets.Add(File.FilePath);
		}
		else if (!File.bLockedByOther)
		{
			State.UnlockTargets.Add(File.FilePath);
		}
		else
		{
			State.ForceUnlockTargets.Add(File);
		}
	}
	return State;
}

FText BuildForceUnlockMessage(const TArray<FDiversionLockMenuFileInfo>& InTargets, int32 MaxListed)
{
	if (InTargets.Num() == 1)
	{
		return FText::Format(LOCTEXT("ForceUnlockConfirm_Single",
			"Release {0}'s lock on '{1}'?\n\nThey will lose the lock's protection: anyone will be able to lock or commit this file while their work is still in progress."),
			FText::FromString(InTargets[0].HolderDisplayName),
			FText::FromString(FPaths::GetBaseFilename(InTargets[0].FilePath)));
	}

	TArray<FText> FileLines;
	const int32 ListedCount = FMath::Min(InTargets.Num(), MaxListed);
	for (int32 i = 0; i < ListedCount; ++i)
	{
		FileLines.Add(FText::Format(LOCTEXT("ForceUnlockConfirm_FileLine", "{0} - {1}"),
			FText::FromString(InTargets[i].HolderDisplayName), FText::FromString(FPaths::GetBaseFilename(InTargets[i].FilePath))));
	}
	if (InTargets.Num() > MaxListed)
	{
		FileLines.Add(FText::Format(LOCTEXT("ForceUnlockConfirm_More", "...and {0} more"), FText::AsNumber(InTargets.Num() - MaxListed)));
	}
	return FText::Format(LOCTEXT("ForceUnlockConfirm_Multi",
		"Release the locks held on {0} files?\n\n{1}\n\nThe holders will lose their locks' protection: anyone will be able to lock or commit these files while their work is still in progress."),
		FText::AsNumber(InTargets.Num()), FText::Join(FText::AsCultureInvariant(TEXT("\n")), FileLines));
}

namespace
{
	FText BuildLockSuccessText(DiversionUtils::EDiversionLockAction InAction, int32 SuccessCount)
	{
		using DiversionUtils::EDiversionLockAction;
		switch (InAction)
		{
		case EDiversionLockAction::Lock:
			return FText::Format(LOCTEXT("LockSucceeded", "Locked {0} {0}|plural(one=file,other=files)"), SuccessCount);
		case EDiversionLockAction::Unlock:
			return FText::Format(LOCTEXT("UnlockSucceeded", "Unlocked {0} {0}|plural(one=file,other=files)"), SuccessCount);
		case EDiversionLockAction::ForceUnlock:
		default:
			return FText::Format(LOCTEXT("ForceUnlockSucceeded", "Force-released {0} {0}|plural(one=lock,other=locks)"), SuccessCount);
		}
	}
}

FText BuildLockTransportFailureNotification(DiversionUtils::EDiversionLockAction InAction,
	int32 SuccessCount, int32 NotProcessedCount)
{
	using DiversionUtils::EDiversionLockAction;

	// Whole sentences per action, so translators never have to fit a verb into someone else's grammar
	FText Message;
	switch (InAction)
	{
	case EDiversionLockAction::Lock:
		Message = LOCTEXT("LockTransportFailed_Lock",
			"Diversion could not reach the lock service - the lock operation did not complete.");
		break;
	case EDiversionLockAction::Unlock:
		Message = LOCTEXT("LockTransportFailed_Unlock",
			"Diversion could not reach the lock service - the unlock operation did not complete.");
		break;
	case EDiversionLockAction::ForceUnlock:
	default:
		Message = LOCTEXT("LockTransportFailed_ForceUnlock",
			"Diversion could not reach the lock service - the force-unlock operation did not complete.");
		break;
	}
	if (SuccessCount > 0)
	{
		Message = FText::Format(LOCTEXT("LockTransportFailed_Partial", "{0}\n{1} before the failure."),
			Message, BuildLockSuccessText(InAction, SuccessCount));
	}
	if (NotProcessedCount > 0)
	{
		Message = FText::Format(LOCTEXT("LockTransportFailed_NotProcessed",
			"{0}\n{1} {1}|plural(one=file was,other=files were) not attempted."),
			Message, NotProcessedCount);
	}
	return FText::Format(LOCTEXT("LockTransportFailed_SeeLog", "{0}\nSee the Output Log for details."), Message);
}

FText BuildLockResultNotification(DiversionUtils::EDiversionLockAction InAction, int32 SuccessCount,
	const TArray<DiversionUtils::FDiversionLockOpFailure>& InFailures, bool& bOutIsFailure)
{
	using DiversionUtils::EDiversionLockAction;

	bOutIsFailure = InFailures.Num() > 0;
	if (!bOutIsFailure)
	{
		if (SuccessCount == 0)
		{
			return FText();
		}
		return BuildLockSuccessText(InAction, SuccessCount);
	}

	// One toast for the whole batch: first failure verbatim, the rest summarized (full
	// detail is in the Output Log via the command's error messages)
	const DiversionUtils::FDiversionLockOpFailure& First = InFailures[0];
	const FText FileName = FText::FromString(FPaths::GetBaseFilename(First.Path));

	FText Message;
	if (!First.Detail.IsEmpty())
	{
		Message = FText::Format(LOCTEXT("LockActionFailed_Detail", "'{0}': {1}"), FileName, FText::FromString(First.Detail));
	}
	else if (InAction == EDiversionLockAction::Lock)
	{
		Message = FText::Format(LOCTEXT("LockFailed_Generic",
			"Could not lock '{0}' - it is already locked by another user."), FileName);
	}
	else if (InAction == EDiversionLockAction::Unlock && First.StatusCode == 403)
	{
		Message = FText::Format(LOCTEXT("UnlockFailed_NotHolder",
			"Could not unlock '{0}' - the lock is held by another user. Only the holder can release it; a repository admin can use Force Unlock."), FileName);
	}
	else if (InAction == EDiversionLockAction::ForceUnlock && First.StatusCode == 403)
	{
		Message = FText::Format(LOCTEXT("ForceUnlockFailed_NotAdmin",
			"Force Unlock failed for '{0}' - releasing another user's lock requires repository admin permissions."), FileName);
	}
	else
	{
		Message = FText::Format(LOCTEXT("LockActionFailed_Generic",
			"Lock operation failed for '{0}' (HTTP {1})."), FileName, FText::AsNumber(First.StatusCode));
	}

	if (InFailures.Num() > 1)
	{
		Message = FText::Format(LOCTEXT("LockActionFailed_More", "{0}\n(+{1} more - see Output Log)"),
			Message, FText::AsNumber(InFailures.Num() - 1));
	}
	// A mixed batch must not read as total failure - lead with what DID succeed
	if (SuccessCount > 0)
	{
		Message = FText::Format(LOCTEXT("LockActionFailed_PartialSuccess", "{0}.\n{1}"),
			BuildLockSuccessText(InAction, SuccessCount), Message);
	}
	return Message;
}

void FDiversionLockContextMenu::Register()
{
	DiversionToolMenus::RegisterDynamicSection(RevisionControlSubMenuName, DiversionLocksOwnerName,
		DiversionLocksSectionName,
		FNewToolMenuDelegate::CreateStatic(&FDiversionLockContextMenu::PopulateSection));
}

void FDiversionLockContextMenu::Unregister()
{
	DiversionToolMenus::UnregisterOwner(DiversionLocksOwnerName);
}

void FDiversionLockContextMenu::PopulateSection(UToolMenu* InMenu)
{
	// Only for the Diversion provider on a lock-eligible (Studio+) repo - otherwise the
	// submenu stays untouched (fail-closed, mirrors the lock API call gating)
	ISourceControlModule& SCModule = ISourceControlModule::Get();
	if (!SCModule.IsEnabled() || SCModule.GetProvider().GetName() != "Diversion")
	{
		return;
	}
	FDiversionProvider& Provider = FDiversionModule::Get().GetProvider();
	if (!Provider.ShouldCheckHardLocks())
	{
		return;
	}

	// The file-data-source variant of this submenu has no asset context - nothing to do
	const UContentBrowserAssetContextMenuContext* Context = InMenu->FindContext<UContentBrowserAssetContextMenuContext>();
	if (Context == nullptr)
	{
		return;
	}

	TArray<FDiversionLockMenuFileInfo> Files;
	for (const FAssetData& AssetData : Context->SelectedAssets)
	{
		const FString FilePath = DiversionUtils::GetFilePathFromAssetData(AssetData);
		if (FilePath.IsEmpty())
		{
			continue;
		}
		TSharedPtr<FDiversionState, ESPMode::ThreadSafe> State = DiversionUtils::GetDiversionStateForPath(FilePath);
		if (!State)
		{
			continue;
		}
		FDiversionLockMenuFileInfo FileInfo;
		FileInfo.FilePath = FilePath;
		FileInfo.bIsLocked = State->FileLock.IsLocked();
		FileInfo.bLockedByOther = State->IsHardLockedByOther(&FileInfo.HolderDisplayName);
		Files.Add(MoveTemp(FileInfo));
	}
	if (Files.Num() == 0)
	{
		return;
	}

	const FDiversionLockMenuState MenuState = ComputeLockMenuState(Files);
	FToolMenuSection& Section = InMenu->AddSection(DiversionLocksSectionName,
		LOCTEXT("DiversionLocksSectionHeading", "Diversion Locks"));

	const bool bCanLock = MenuState.LockTargets.Num() > 0;
	Section.AddMenuEntry(
		"DiversionLockFiles",
		LOCTEXT("LockEntry", "Lock"),
		bCanLock ?
			LOCTEXT("LockEntry_Tooltip", "Lock the selected files so only you can commit changes to them (others can still save locally).") :
			LOCTEXT("LockEntry_DisabledTooltip", "All selected files are already locked."),
		FSlateIcon(FAppStyle::GetAppStyleSetName(), "Icons.Lock"),
		FUIAction(
			FExecuteAction::CreateStatic(&FDiversionLockContextMenu::ExecuteLockAction,
				DiversionUtils::EDiversionLockAction::Lock, MenuState.LockTargets),
			FCanExecuteAction::CreateLambda([bCanLock]() { return bCanLock; })));

	const bool bCanUnlock = MenuState.UnlockTargets.Num() > 0;
	Section.AddMenuEntry(
		"DiversionUnlockFiles",
		LOCTEXT("UnlockEntry", "Unlock"),
		bCanUnlock ?
			LOCTEXT("UnlockEntry_Tooltip", "Release your lock on the selected files.") :
			LOCTEXT("UnlockEntry_DisabledTooltip", "No selected file is locked by you."),
		FSlateIcon(FAppStyle::GetAppStyleSetName(), "Icons.Unlock"),
		FUIAction(
			FExecuteAction::CreateStatic(&FDiversionLockContextMenu::ExecuteLockAction,
				DiversionUtils::EDiversionLockAction::Unlock, MenuState.UnlockTargets),
			FCanExecuteAction::CreateLambda([bCanUnlock]() { return bCanUnlock; })));

	// Rare and destructive - only offered when a selected file is actually locked by
	// someone else (the server rejects non-admins with 403; no client-side role check)
	if (MenuState.ForceUnlockTargets.Num() > 0)
	{
		Section.AddMenuEntry(
			"DiversionForceUnlockFiles",
			LOCTEXT("ForceUnlockEntry", "Force Unlock"),
			LOCTEXT("ForceUnlockEntry_Tooltip", "Release another user's lock on the selected files. Requires repository admin permissions."),
			FSlateIcon(FAppStyle::GetAppStyleSetName(), "Icons.Unlock"),
			FUIAction(FExecuteAction::CreateStatic(&FDiversionLockContextMenu::ShowForceUnlockConfirmation,
				MenuState.ForceUnlockTargets)));
	}
}

void FDiversionLockContextMenu::ExecuteLockAction(DiversionUtils::EDiversionLockAction InAction, TArray<FString> InFiles)
{
	if (InFiles.Num() == 0)
	{
		return;
	}
	FDiversionProvider& Provider = FDiversionModule::Get().GetProvider();

	auto Operation = ISourceControlOperation::Create<FUpdateFileLock>();
	Operation->SetLockAction(InAction);
	const int32 FileCount = InFiles.Num();
	// Synchronous by design: this is a deliberate user action - when the click returns, the
	// lock state (and its icons) must reflect the result. The API calls use the short
	// game-thread timeouts (see SyncUpdateFileLock.cpp) so a hung backend cannot stall long.
	Provider.Execute(Operation, nullptr, InFiles, EConcurrency::Synchronous,
		FSourceControlOperationComplete::CreateLambda(
			[InAction, FileCount](const FSourceControlOperationRef&, ECommandResult::Type InResult)
			{
				const TCHAR* ActionName =
					InAction == DiversionUtils::EDiversionLockAction::Lock ? TEXT("lock") :
					InAction == DiversionUtils::EDiversionLockAction::Unlock ? TEXT("unlock") : TEXT("force_unlock");
				auto SendAnalyticsOperation = ISourceControlOperation::Create<FSendAnalytics>();
				SendAnalyticsOperation->SetEventName(FText::FromString("UE Lock Action Executed"));
				SendAnalyticsOperation->SetEventProperties({
					{"action", ActionName},
					{"file_count", FString::FromInt(FileCount)},
					{"result", InResult == ECommandResult::Succeeded ? "success" : "failed"}});
				FDiversionModule::Get().GetProvider().Execute(SendAnalyticsOperation, nullptr,
					TArray<FString>(), EConcurrency::Asynchronous);
			}));
}

void FDiversionLockContextMenu::ShowForceUnlockConfirmation(TArray<FDiversionLockMenuFileInfo> InTargets)
{
	if (InTargets.Num() == 0)
	{
		return;
	}

	TSharedRef<SWindow> DialogWindow = SNew(SWindow)
		.Title(LOCTEXT("ForceUnlockDialogTitle", "Diversion - Force Unlock"))
		.SizingRule(ESizingRule::Autosized)
		.AutoCenter(EAutoCenter::PreferredWorkArea)
		.SupportsMinimize(false).SupportsMaximize(false);

	const int X_BUTTON_IDENTIFIER = -1;
	const int CANCEL_BUTTON_IDENTIFIER = 0;
	const int FORCE_UNLOCK_BUTTON_IDENTIFIER = 1;
	TArray<TSharedRef<FConfirmationOption>> Buttons = {
		MakeShared<FConfirmationOption>(LOCTEXT("ForceUnlockConfirmButton", "Force Unlock"), FORCE_UNLOCK_BUTTON_IDENTIFIER,
			&FAppStyle::Get().GetWidgetStyle<FButtonStyle>("FlatButton.Danger"), false),
		MakeShared<FConfirmationOption>(LOCTEXT("ForceUnlockCancelButton", "Cancel"), CANCEL_BUTTON_IDENTIFIER,
			&FAppStyle::Get().GetWidgetStyle<FButtonStyle>("PrimaryButton"), false)
	};

	TSharedRef<SConfirmationDialog> ConfirmationDialog = SNew(SConfirmationDialog)
		.ParentWindow(DialogWindow)
		.Message(BuildForceUnlockMessage(InTargets))
		.Buttons(Buttons);

	DialogWindow->SetContent(ConfirmationDialog);
	FSlateApplication::Get().AddModalWindow(DialogWindow, nullptr);

	auto SelectedActionText = "";
	switch (ConfirmationDialog->GetResult())
	{
	case FORCE_UNLOCK_BUTTON_IDENTIFIER:
	{
		TArray<FString> Paths;
		for (const FDiversionLockMenuFileInfo& Target : InTargets)
		{
			Paths.Add(Target.FilePath);
		}
		ExecuteLockAction(DiversionUtils::EDiversionLockAction::ForceUnlock, MoveTemp(Paths));
		SelectedActionText = "Force Unlock";
		break;
	}
	case CANCEL_BUTTON_IDENTIFIER:
	case X_BUTTON_IDENTIFIER:
	default:
		SelectedActionText = "Cancel";
		break;
	}
	DialogWindow->RequestDestroyWindow();

	auto SendAnalyticsOperation = ISourceControlOperation::Create<FSendAnalytics>();
	SendAnalyticsOperation->SetEventName(FText::FromString("UE Force Unlock Dialog Interacted"));
	SendAnalyticsOperation->SetEventProperties({{"chosen_action", SelectedActionText}});
	FDiversionModule::Get().GetProvider().Execute(SendAnalyticsOperation, nullptr,
		TArray<FString>(), EConcurrency::Asynchronous);
}

